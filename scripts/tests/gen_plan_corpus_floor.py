#!/usr/bin/env python3
"""Regenerate scripts/tests/fixtures/plan_corpus_floor.json from a plans/ directory.

The manifest is a golden master of what the extractor reads from the plans that existed when
it was generated: it blesses whatever the extractor emits today, so regenerate it only as a
deliberate, reviewed act (read the diff), never to make a red test green. It is derived, never
hand-typed: a hand-copied corpus goes stale while reading as authoritative.

A manifest SHORTER than the one it replaces means plans were missing from the directory this
read; read the diff before committing it. Most entries record zero checks and detect only a
falsely widened matcher, so the entry count overstates the regression coverage.

Usage: gen_plan_corpus_floor.py --plans DIR --through YYYY-MM-DD --out FILE

Only plans whose filename date is on or before --through are recorded; later plans stay exempt.
There is no default output path: a default would make every run a writer of real state.
"""

from __future__ import annotations

import argparse
import datetime
import importlib.util
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MODULE = REPO / "scripts" / "plan-rehearse.py"


def load_extractor():
    spec = importlib.util.spec_from_file_location("plan_rehearse", MODULE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.extract


def build(plans_dir, through, extract):
    """Map plan filename -> [total, unpaired] for plans dated on or before `through`."""
    files = {}
    for path in sorted(Path(plans_dir).glob("*.md")):
        m = re.match(r"(\d{4}-\d{2}-\d{2})-", path.name)
        if not m or m.group(1) > through:
            continue
        checks = extract(path.read_text(encoding="utf-8"))[0]
        files[path.name] = [len(checks), sum(c.command is None for c in checks)]
    return files


def render(files, through):
    """Deterministic JSON with one line per file, so a diff names the file that changed."""
    zero = sum(1 for t, _ in files.values() if t == 0)
    about = (
        "Generated by scripts/tests/gen_plan_corpus_floor.py; do not hand-edit. Golden master of "
        f"the extractor over plans dated through {through}. {zero} of these {len(files)} entries "
        "record zero checks and detect only a falsely widened matcher, so the entry count is not "
        "the regression coverage. Regenerate only after reading the diff."
    )
    items = sorted(files.items())
    lines = [
        "{",
        f' "_about": {json.dumps(about)},',
        f' "through": {json.dumps(through)},',
        ' "files": {',
    ]
    for i, (name, pair) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f"  {json.dumps(name)}: {json.dumps(pair)}{comma}")
    lines += [" }", "}"]
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--plans", required=True, type=Path)
    ap.add_argument("--through", required=True)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)
    try:
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.through):
            raise ValueError(args.through)
        datetime.date.fromisoformat(args.through)
    except ValueError:
        print("error: --through must be a real date, YYYY-MM-DD", file=sys.stderr)
        return 2
    plans = args.plans.resolve()
    out = args.out.resolve()
    if plans in out.parents:
        print("error: refusing to write inside the plans directory", file=sys.stderr)
        return 2
    files = build(plans, args.through, load_extractor())
    if not files:
        print(
            f"error: no plan dated on or before {args.through} in {plans}",
            file=sys.stderr,
        )
        return 2
    out.write_text(render(files, args.through), encoding="utf-8")
    total = sum(t for t, _ in files.values())
    unpaired = sum(u for _, u in files.values())
    nonzero = sum(1 for _, u in files.values() if u)
    print(
        f"files={len(files)} checks={total} unpaired={unpaired} nonzero_files={nonzero}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
